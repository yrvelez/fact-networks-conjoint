def arm_str(v):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return None
    sv = str(v).strip()
    try:
        f = float(sv)
    except ValueError:
        return sv
    return str(int(f)) if f.is_integer() else sv

def cat_set(est):
    """Categorical covariates for one hypothesis: codebook-labelled columns, plus estimator.categorical,
    minus estimator.continuous (lets a plan pin an ordinal item as continuous, as the original model did)."""
    return (CATEGORICAL | set(est.get("categorical") or [])) - set(est.get("continuous") or [])

def term(c, cats=CATEGORICAL):
    return f"C({c})" if c in cats else c

def fit(df, formula, est):
    kw = {}
    cl = est.get("cluster")
    if cl:
        kw = dict(cov_type="cluster", cov_kwds={"groups": df[cl]})
    else:
        kw = dict(cov_type=est.get("robust") or "HC2")
    w = est.get("weights")
    model = smf.wls(formula, data=df, weights=df[w]) if w else smf.ols(formula, data=df)
    return model.fit(**kw)

def centered(d, covs, cats=CATEGORICAL):
    """Lin (2013): covariates centred at their sample means; categorical covariates become centred dummies.
    Returns (data, list of centred column names)."""
    cols = []
    for c in covs:
        if c in cats:
            dums = pd.get_dummies(d[c].astype(str), prefix=c, drop_first=True, dtype=float)
            for k in dums.columns:
                name = "".join(ch if ch.isalnum() else "_" for ch in k) + "_c"
                d[name] = dums[k] - dums[k].mean()
                cols.append(name)
        else:
            d[c + "_c"] = pd.to_numeric(d[c], errors="coerce") - pd.to_numeric(d[c], errors="coerce").mean()
            cols.append(c + "_c")
    return d, cols

def build_formula(y, est, covs, d, arm_term="treat"):
    kind = est.get("kind", "ols")
    if kind == "diff_means" or not covs:
        return f"{y} ~ {arm_term}", d
    cats = cat_set(est)
    if kind == "lin":
        d, cc = centered(d, covs, cats)
        return f"{y} ~ {arm_term} * ({' + '.join(cc)})", d
    return f"{y} ~ {arm_term}" + "".join(f" + {term(c, cats)}" for c in covs), d

def tidy(res, analysis_id):
    ci = res.conf_int()
    rows = []
    for t in res.params.index:
        rows.append({"analysis_id": analysis_id, "term": t, "estimate": res.params[t], "std_error": res.bse[t],
                     "statistic": res.tvalues[t], "p_value": res.pvalues[t], "conf_low": ci.loc[t, 0], "conf_high": ci.loc[t, 1]})
    return pd.DataFrame(rows)

def directional_p(est, p, direction):
    """p-value matching the hypothesis: one-sided for a stated direction (half the two-sided p when the
    estimate has the predicted sign, 1 - p/2 otherwise), two-sided otherwise."""
    if direction == "positive":
        return float(p / 2 if est > 0 else 1 - p / 2)
    if direction == "negative":
        return float(p / 2 if est < 0 else 1 - p / 2)
    return float(p)

def supported(est, p, direction):
    return bool(directional_p(est, p, direction) < ALPHA)

def pool(effects, variances):
    """Random-effects pooled estimate (iterated tau^2; DerSimonian-Laird fallback).
    The arm effects share one control group, so they are not independent: the pooled SE is approximate."""
    from statsmodels.stats.meta_analysis import combine_effects
    eff, var = np.asarray(effects, float), np.asarray(variances, float)
    try:
        cr = combine_effects(eff, var, method_re="iterated")
        if not np.isfinite(cr.tau2):
            raise ValueError("tau2 not finite")
        method = "iterated"
    except Exception:
        cr = combine_effects(eff, var, method_re="dl")
        method = "dl"
    est, se = float(cr.mean_effect_re), float(cr.sd_eff_w_re)
    p = float(2 * sps.norm.sf(abs(est / se))) if se > 0 else float("nan")
    i2 = float(max(0.0, min(1.0, cr.i2))) if np.isfinite(cr.i2) else float("nan")
    return {"estimate": est, "std_error": se, "p_value": p, "tau2": float(cr.tau2), "i2": i2, "method": method,
            "conf_low": est - 1.96 * se, "conf_high": est + 1.96 * se}

